const fs = require('fs');
const h = fs.readFileSync('guides/budget-bass-like-expensive.html', 'utf8');
const he = fs.readFileSync('guides/budget-bass-like-expensive_es.html', 'utf8');
const G = JSON.parse(fs.readFileSync('data/guides.json', 'utf8')).find(x => x.id === 'budget-bass-like-expensive');
const OUT = ['Affinity Series Precision Bass PJ', 'Hofner', 'American Professional II', 'Ultra II Precision'];
const checks = [];
OUT.forEach(w => checks.push(['fuera "' + w + '" EN', !h.includes(w)]));
OUT.forEach(w => checks.push(['fuera "' + w + '" ES', !he.includes(w)]));
checks.push(['10 tarjetas EN', (h.match(/class="guide-product-card"/g) || []).length === 10]);
checks.push(['10 tarjetas ES', (he.match(/class="guide-product-card"/g) || []).length === 10]);
checks.push(['10 columnas tabla', (h.match(/<th[^>]*>/g) || []).length >= 11]);
checks.push(['veredicto Schecter EN', h.includes('Schecter Stiletto Stealth 4 for metal')]);
checks.push(['veredicto Schecter ES', he.includes('Schecter Stiletto Stealth 4 para metal')]);
checks.push(['veredicto Thunderbird nicho EN', h.includes('niche neck-through rock classic')]);
checks.push(['conclusion neck-dive EN', h.includes('neck-dives with a light strap')]);
checks.push(['conclusion neck-dive ES', he.includes('cabecea con correa ligera')]);
checks.push(['sin "A Closer Look" EN', !h.includes('A Closer Look')]);
checks.push(['sin "análisis detallado" ES', !he.includes('an\u00e1lisis detallado')]);
checks.push(['review V5 pasiva EN', h.includes('genuinely, fully passive')]);
checks.push(['review Schecter Diamond EN', h.includes('Schecter Diamond P in the neck')]);
checks.push(['review ESP SB-4 EN', h.includes('passive ESP SB-4 humbuckers')]);
checks.push(['FAQ4 Squier/Fender', he.includes('Bajos Squier y Epiphone')]);
checks.push(['FAQ5 upgrade', h.includes('single biggest upgrade')]);
checks.push(['10 reviews (1 prod c/u)', G.sections.filter(s => (s.products || []).length === 1).length === 10]);
checks.push(['paridad veredictos 4+4', G.verdictProsCons.every(v => v.pros.length === 4 && v.cons.length === 4 && v.pros_es.length === 4 && v.cons_es.length === 4)]);
checks.push(['sin desalineacion tabla', G.productTable.rows.every(r => r.values.length === 10 && r.values.every(v => v.value && v.value_es))]);
checks.push(['cada producto con review', G.featuredProducts.every(id => G.sections.some(s => (s.products || []).length === 1 && s.products[0] === id))]);
checks.push(['headings unicos', new Set(G.sections.map(s => s.heading)).size === G.sections.length]);
let ok = 0;
checks.forEach(([n, v]) => { if (v) ok++; console.log((v ? 'OK  ' : 'FALLO ') + n); });
console.log(ok + '/' + checks.length);
